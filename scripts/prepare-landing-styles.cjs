const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');

// Keep the imported site's framework and resets inside its homepage wrapper.
const sources = [
  'bootstrap/dist/css/bootstrap.min.css',
  'swiper/css',
  'swiper/css/navigation',
  'swiper/css/pagination',
  'swiper/css/effect-coverflow',
  'aos/dist/aos.css',
];
const vendor = sources.map(name => fs.readFileSync(require.resolve(name), 'utf8')).join('\n');
const custom = fs.readFileSync(path.join(__dirname, '../src/components/landing/design.css'), 'utf8');
const css = postcss.parse(vendor + '\n' + custom);
const iconsPath = require.resolve('bootstrap-icons/font/bootstrap-icons.css');
const fontDir = path.join(__dirname, '../public/landing/fonts');
fs.mkdirSync(fontDir, { recursive: true });
for (const name of ['bootstrap-icons.woff', 'bootstrap-icons.woff2']) {
  fs.copyFileSync(path.join(path.dirname(iconsPath), 'fonts', name), path.join(fontDir, name));
}
const icons = fs.readFileSync(iconsPath, 'utf8').replaceAll('./fonts/', '/landing/fonts/');
css.walkAtRules(/^(charset|import)$/, rule => rule.remove());
css.walkComments(comment => { if (comment.text.includes('sourceMappingURL')) comment.remove(); });
css.walkRules(rule => {
  rule.selector = rule.selector.replace(/:root|(?<![\w.-])(?:html|body)(?![\w-])/g, ':scope');
});
fs.writeFileSync(path.join(__dirname, '../src/components/landing/landing.css'),
  '/* Generated by scripts/prepare-landing-styles.cjs */\n' +
  icons + '\n' +
  '@scope (.chirpii-landing) {\n' + css.toString() + '\n' +
  ':scope { letter-spacing: normal; }\n' +
  'h1,h2,h3,h4,h5,h6 { font-family: var(--font-main); letter-spacing: normal; }\n}\n' +
  'html:has(.chirpii-landing) { scroll-behavior: smooth; scroll-padding-top: 80px; }\n');
